@texture("block/pink_petals.png")
def pink_petals():
    # Three full flowers and three buds, lying flat.
    big = """
.lpl.
lpppl
ppcpp
lpppl
.lpl.
"""
    small = """
.p.
pcp
.p.
"""
    legend = {"p": "#f4a6c8", "l": "#fbd0e2", "c": "#e0609a"}
    c = Canvas()
    for x, y in ((9, 1), (1, 7), (9, 10)):
        c.draw(big, legend, x, y)
    for x, y in ((2, 1), (13, 7), (5, 13)):
        c.draw(small, legend, x, y)
    return c


VINE = {"v": "#4a6a24", "l": "#5f8f2e", "o": "#f0901e", "O": "#ffd060"}


@texture("block/cave_vines_lit.png", "block/cave_vines_lit_e.png")
def cave_vines_lit(path):
    """A leafy vine hung with glow berries. The `_e` picture is what glows: the berries."""
    legend = dict(VINE)
    if path.endswith("_e.png"):
        legend["v"] = legend["l"] = None
    return sprite(
        """
......vv........
.....lvvl.......
....llvl.ll.....
...l.lv.llll....
..ll..vv..l.....
.lll.lvvl.......
..l..oovl..ll...
....oOoov.lll...
....oooovl.l....
.....oovvl......
...ll..vv.......
..llll.vv..l....
...l..lvv.lll...
.....ll.voo.l...
......l.oOoo....
........ooo.....
""",
        legend,
    )
